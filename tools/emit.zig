pub fn commands(g: *Generator) Error![]const u8 {
    var out: Out = .empty;
    try header(g, &out, "The command tables: what to load from a Vulkan implementation, by scope.");
    try put(g, &out,
        \\//!
        \\//! Ordinary structs of the kind `dispatch.load` fills in, one per scope. A field is
        \\//! the command's name without `vk`, with its first letter lower-case: `cmdDraw` is
        \\//! `vkCmdDraw`. A plain function pointer is a command every Vulkan 1.0 device has;
        \\//! an optional one is from a later version or an extension, and is `null` on a
        \\//! device that has neither. A promoted command's older name is in `aliases`.
        \\
        \\const types = @import("types.zig");
        \\const call = @import("../types.zig").call;
        \\
    , .{});

    const tiers = [_]gen.Tier{ .global, .instance, .device };
    const blurb = [_][]const u8{
        "What exists before there is an instance, resolved against a null one.",
        "What dispatches on an instance or a physical device, through the loader's trampoline.",
        "What dispatches on a device, a queue or a command buffer, straight into the driver.",
    };
    const table_name = [_][]const u8{ "Global", "Instance", "Device" };

    for (tiers, 0..) |tier, tier_index| {
        var list: std.ArrayList(gen.WantedCommand) = .empty;
        for (g.commands.items) |c| if (c.tier == tier) try list.append(g.arena, c);
        std.mem.sort(gen.WantedCommand, list.items, {}, commandLess);

        try put(g, &out, "\n/// {s}\npub const {s} = struct {{\n", .{ blurb[tier_index], table_name[tier_index] });

        var any_alias = false;
        for (list.items, 0..) |c, index| {
            if (index > 0) try put(g, &out, "\n", .{});
            try put(g, &out, "    /// {s}\n", .{c.name});
            if (!c.required) try put(g, &out, "    ///\n    /// Optional: from {s}.\n", .{c.provenance});

            const optional = if (c.required) "" else "?";
            try put(g, &out, "    {s}: {s}*const fn (\n", .{ try g.id(c.field), optional });

            var siblings: std.ArrayList(reg.Decl) = .empty;
            for (c.params) |p| try siblings.append(g.arena, p.decl);
            for (c.params) |p| {
                try put(g, &out, "        {s}: {s},\n", .{ p.zig_name, try g.declType("types.", p.decl, siblings.items, .param) });
            }
            try put(g, &out, "    ) callconv(call) {s},\n", .{try g.declType("types.", c.ret, &.{}, .ret)});

            if (c.aliases.len > 0) any_alias = true;
            switch (tier) {
                .global => g.summary.global += 1,
                .instance => g.summary.instance += 1,
                .device => g.summary.device += 1,
            }
            if (!c.required) g.summary.optional += 1;
        }

        if (any_alias) {
            try put(g, &out, "\n    /// Promoted commands answer to the name they had as an extension, on a\n    /// driver old enough to have only that.\n    pub const aliases = .{{\n", .{});
            for (list.items) |c| {
                if (c.aliases.len == 0) continue;
                try put(g, &out, "        .{s} = .{{", .{try g.id(c.field)});
                for (c.aliases, 0..) |a, i| try put(g, &out, "{s}\"{s}\"", .{ if (i > 0) ", " else "", a });
                try put(g, &out, "}},\n", .{});
            }
            try put(g, &out, "    }};\n", .{});
        }
        try put(g, &out, "}};\n", .{});
    }
    return out.items;
}

fn commandLess(_: void, a: gen.WantedCommand, b: gen.WantedCommand) bool {
    return a.order < b.order;
}

