pub fn layoutZig(g: *Generator, rows: []const Row) Error![]const u8 {
    var out: Out = .empty;
    try header(g, &out, "What Zig makes of every struct and every enumerant, to be compared with what C makes of them.");
    try put(g, &out,
        \\//!
        \\//! `values[i]` is the number Zig gets for `labels[i]`; `layout.c` computes the same
        \\//! list from the real Vulkan headers, in the same order. Every entry is a size, an
        \\//! alignment, a member offset, an enumerant or a constant. The test that compares
        \\//! the two is in `oracle.zig`.
        \\
        \\const types = @import("types.zig");
        \\
        \\/// An enum's number, as the bits C would print for it.
        \\fn e(value: anytype) u64 {{
        \\    return @bitCast(@as(i64, @intFromEnum(value)));
        \\}}
        \\
        \\/// A flags value's bits.
        \\fn f(value: anytype) u64 {{
        \\    const Int = @Int(.unsigned, @bitSizeOf(@TypeOf(value)));
        \\    return @as(Int, @bitCast(value));
        \\}}
        \\
        \\pub const values = blk: {{
        \\    @setEvalBranchQuota(10_000_000);
        \\    break :blk [_]u64{{
        \\
    , .{});
    for (rows) |row| try put(g, &out, "        {s},\n", .{row.zig});
    try put(g, &out, "    }};\n}};\n\npub const labels = [_][]const u8{{\n", .{});
    for (rows) |row| try put(g, &out, "    \"{s}\",\n", .{row.label});
    try put(g, &out, "}};\n", .{});
    return out.items;
}

pub fn layoutC(g: *Generator, rows: []const Row) Error![]const u8 {
    var out: Out = .empty;
    try put(g, &out,
        \\/* SPDX-License-Identifier: BSL-1.0 */
        \\
        \\/*
        \\ * GENERATED by tools/genvk.zig from the Vulkan registry. Do not edit: change
        \\ * tools/wanted.zon and run `zig build gen -Dvk-xml=<path to vk.xml>`.
        \\ *
        \\ * What the real Vulkan headers make of every struct and enumerant that
        \\ * types.zig declares: sizes, alignments, member offsets, values. `layout.zig`
        \\ * lists the same things in the same order with the numbers Zig gets.
        \\ *
        \\ *     zig cc -I<Vulkan SDK>/Include -DFLUXION_MAIN layout.c
        \\ *
        \\ * prints one number per line. Compiled with -S for another target, the table
        \\ * is in the assembly and nothing has to run.
        \\ */
        \\
        \\#include <stddef.h>
        \\#include <stdint.h>
        \\
    , .{});

    // The native types the platform headers name and do not define.
    try put(g, &out, "\n/* The platforms' own types, as much as Vulkan's headers need of them. */\n", .{});
    for (g.w.platform_types) |p| try put(g, &out, "{s}\n", .{p.c});

    try put(g, &out, "\n#include <vulkan/vulkan_core.h>\n", .{});

    // The platform headers whose structs are in the list.
    var platforms: std.ArrayList([]const u8) = .empty;
    for (g.r.providers) |p| {
        if (!g.isSelected(p.name)) continue;
        const platform = p.platform orelse continue;
        var used = false;
        for (p.requires) |req| for (req.types) |t| {
            if (g.needed.contains(g.r.canonical(t))) used = true;
        };
        if (!used) continue;
        var seen = false;
        for (platforms.items) |x| if (std.mem.eql(u8, x, platform)) {
            seen = true;
        };
        if (!seen) try platforms.append(g.arena, platform);
    }
    std.mem.sort([]const u8, platforms.items, {}, lessThanString);
    for (platforms.items) |p| try put(g, &out, "#include <vulkan/vulkan_{s}.h>\n", .{p});

    try put(g, &out,
        \\
        \\const unsigned long long fluxion_layout[] = {{
        \\
    , .{});
    for (rows) |row| try put(g, &out, "    {s}, /* {s} */\n", .{ row.c, row.label });
    try put(g, &out,
        \\}};
        \\
        \\#ifdef FLUXION_MAIN
        \\#include <stdio.h>
        \\int main(void) {{
        \\    for (size_t i = 0; i < sizeof(fluxion_layout) / sizeof(fluxion_layout[0]); i++)
        \\        printf("%llu\n", fluxion_layout[i]);
        \\    return 0;
        \\}}
        \\#endif
        \\
    , .{});
    return out.items;
}
