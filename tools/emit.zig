//! The writers: a resolved `Generator` in, Zig and C source out.
//!
//! Everything here is a walk over the registry in its own order, so the output
//! does not depend on the order things were asked for in `wanted.zon` or on
//! anything that varies between runs.

const std = @import("std");
const Allocator = std.mem.Allocator;

const gen = @import("gen.zig");
const reg = @import("registry.zig");
const names = @import("names.zig");
const Generator = gen.Generator;
const Error = gen.Error;
const fail = gen.fail;

const Out = std.ArrayList(u8);

fn put(g: *Generator, out: *Out, comptime fmt: []const u8, args: anytype) Error!void {
    try out.print(g.arena, fmt, args);
}

/// One thing the C oracle measures and Zig has an opinion on, with both
/// spellings, so the two files cannot list them in different orders.
pub const Row = struct {
    label: []const u8,
    /// A Zig expression for a `u64`, in `layout.zig`, where `types` is the
    /// generated types.
    zig: []const u8,
    /// A C expression of type `unsigned long long`.
    c: []const u8,
};

const header_text =
    \\// SPDX-License-Identifier: BSL-1.0
    \\
    \\//! {s}
    \\//!
    \\//! GENERATED by `tools/genvk.zig` from the Vulkan registry. Do not edit: change
    \\//! `tools/wanted.zon` and run `zig build gen -Dvk-xml=<path to vk.xml>`.
    \\//!
    \\//! Registry: vk.xml, VK_HEADER_VERSION {s}.
    \\
;

fn header(g: *Generator, out: *Out, what: []const u8) Error!void {
    try put(g, out, header_text, .{ what, g.r.header_version });
}

fn banner(g: *Generator, out: *Out, title: []const u8) Error!void {
    try put(g, out, "\n// -------------------------------------------------------------------------\n// {s}\n// -------------------------------------------------------------------------\n\n", .{title});
}

/// A registry comment as a `///` line: one line, no leading `//`.
fn docLine(g: *Generator, out: *Out, indent: []const u8, text: []const u8) Error!void {
    var clean: std.ArrayList(u8) = .empty;
    var last_space = true;
    for (text) |c| {
        const is_space = c == ' ' or c == '\n' or c == '\r' or c == '\t';
        if (is_space) {
            if (!last_space) try clean.append(g.arena, ' ');
            last_space = true;
        } else {
            try clean.append(g.arena, c);
            last_space = false;
        }
    }
    var line = std.mem.trim(u8, clean.items, " ");
    if (std.mem.startsWith(u8, line, "//")) line = std.mem.trim(u8, line[2..], " ");
    if (line.len == 0) return;
    try put(g, out, "{s}/// {s}\n", .{ indent, line });
}

/// The `///` block above a declaration: the registry's name, and its comment.
fn doc(g: *Generator, out: *Out, indent: []const u8, reg_name: []const u8, comment: ?[]const u8) Error!void {
    try put(g, out, "{s}/// {s}\n", .{ indent, reg_name });
    if (comment) |c| {
        try put(g, out, "{s}///\n", .{indent});
        try docLine(g, out, indent, c);
    }
}

fn lessThanString(_: void, a: []const u8, b: []const u8) bool {
    return std.mem.lessThan(u8, a, b);
}

/// Every name a selected feature or extension asks for, as a set: the names of
/// types are how a promoted type's old alias is recognised as wanted.
fn requiredTypeNames(g: *Generator) Error!gen.Set {
    var set: gen.Set = .empty;
    for (g.r.providers) |p| {
        if (!g.isSelected(p.name)) continue;
        for (p.requires) |req| for (req.types) |t| try set.put(g.arena, t, {});
    }
    return set;
}

